export function normalizeSymbol(symbol: string): string {
  return symbol.trim().toUpperCase().split(':').pop() ?? '';
}

export function findTrackedSymbol(symbol: string): TrackedSymbol | undefined {
  const normalizedSymbol = normalizeSymbol(symbol);

  return TRACKED_SYMBOLS.find(
    (trackedSymbol) => trackedSymbol.symbol === normalizedSymbol,
  );
}

export function getSymbolType(symbol: string): TrackedSymbolType | undefined {
  return findTrackedSymbol(symbol)?.type;
}

export function getSymbolCategory(symbol: string): string | undefined {
  return findTrackedSymbol(symbol)?.category;
}
